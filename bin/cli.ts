#!/usr/bin/env node

import { Command } from 'commander';
import { generate } from '../src/commands/generate.ts';

const program = new Command();

program
  .name('neucli')
  .description('Generate React + Tailwind websites from YAML config')
  .version('0.1.0');

program
  .command('generate')
  .description('Generate a website from a YAML config file')
  .argument('<config>', 'Path to the YAML config file')
  .option('-o, --output <dir>', 'Output directory', './output')
  .option('--force', 'Overwrite generated files you edited by hand, and files neucli did not write', false)
  .option('--migrate', 'Switch a folder generated by an older neucli to the src/neucli/ layout', false)
  .option('--keep-stale', 'Keep generated files the config no longer produces', false)
  .option('--allow-edited', 'Exit with 0 even when hand-edited generated files were skipped', false)
  .action((config, options) => generate(config, options));

program.parse();
