import fs from 'fs';
import path from 'path';
import chalk from 'chalk';
import { readConfig } from './parser.ts';
import { scaffoldProject, usesRouting } from './project.ts';
import { appSource, componentSource, pageSource } from './codegen.ts';
import { Output, readManifest, removeEmptyDirs } from './output.ts';
import type { Report } from './output.ts';
import { OUT, OLD_LAYOUT, fileComponentPath } from './paths.ts';
import { validate, pageComponentName, instancesIn, pageParentFlows, layoutOf, isFileComponent } from '../core/index.ts';
import type { ComponentDef, Config, PropDef } from '../core/index.ts';

export { Report } from './output.ts';

export interface PipelineOptions {
  /** Keep tracked files the config no longer produces. */
  keepStale?: boolean;
  /** Overwrite hand-edited files and files neucli doesn't own. */
  force?: boolean;
  /** Switch a folder generated by an older neucli (src/components...) to src/neucli/. */
  migrate?: boolean;
  /** Silence progress output (tests). */
  quiet?: boolean;
}

/** A refusal the user can act on (old layout, files in the way); printed without a stack. */
export class GenerateError extends Error {}

/** Parse + validate; throws with every error listed. */
export function loadConfig(configPath: string): { config: Config; warnings: string[] } {
  const result = validate(readConfig(configPath));
  if (!result.config) {
    throw new Error(`Config validation failed:\n${result.errors.map(e => `  - ${e}`).join('\n')}`);
  }
  return { config: result.config, warnings: result.warnings };
}

/** Components reachable from pages and layouts; unused definitions aren't generated. */
function usedComponents(config: Config): string[] {
  const used = new Set<string>();
  const queue: string[] = [];
  const add = (name: string) => {
    if (!used.has(name)) {
      used.add(name);
      queue.push(name);
    }
  };
  for (const page of config.pages) {
    page.sections.forEach(s => instancesIn(s).forEach(add));
    const layout = layoutOf(config, page);
    if (layout) add(layout);
  }
  while (queue.length) {
    const def = config.components?.[queue.pop()!];
    if (def?.root) instancesIn(def.root).forEach(add);
  }
  return [...used].sort();
}

/** An old-layout folder: written by neucli before the manifest existed. */
function isOldLayout(dir: string): boolean {
  return fs.existsSync(path.join(dir, OUT.lock)) && !fs.existsSync(path.join(dir, OUT.manifest));
}

function oldLayoutFiles(dir: string): string[] {
  const out: string[] = [];
  for (const d of OLD_LAYOUT.dirs) {
    const abs = path.join(dir, d);
    if (!fs.existsSync(abs)) continue;
    for (const f of fs.readdirSync(abs)) {
      if (/\.(tsx|ts)$/.test(f)) out.push(`${d}/${f}`);
    }
  }
  for (const f of OLD_LAYOUT.files) if (fs.existsSync(path.join(dir, f))) out.push(f);
  return out;
}

const TS_TYPE: Record<PropDef['type'], string> = {
  text: 'string', url: 'string', image: 'string', number: 'number', boolean: 'boolean',
};

/** A starting point for a `file:` component that doesn't exist yet. Yours from then on. */
function fileComponentStub(name: string, def: ComponentDef & { file: string }): string {
  const props = Object.entries((def.props ?? {}) as Record<string, PropDef>);
  const lines = [
    ...props.map(([p, d]) => `  ${p}?: ${TS_TYPE[d.type]};`),
    '  children?: ReactNode;',
    '  className?: string;',
  ];
  const params = [...props.map(([p]) => p), 'children', 'className'];
  return `import type { ReactNode } from 'react';

// neucli wrote this because components.${name} points here and the file didn't exist.
// It's yours now: neucli won't change or delete it.

export interface ${name}Props {
${lines.join('\n')}
}

export default function ${name}({ ${params.join(', ')} }: ${name}Props) {
  return (
    <div className={className}>
      <p>${name}: edit src/${fileComponentPath(def.file)}</p>
      {children}
    </div>
  );
}
`;
}

export async function runPipeline(configPath: string, outputDir: string, options: PipelineOptions = {}): Promise<Report> {
  const log = options.quiet ? () => {} : (msg: string) => console.log(msg);

  log(chalk.dim('  Reading and validating config...'));
  const { config, warnings } = loadConfig(configPath);
  for (const w of warnings) log(chalk.yellow(`  ! ${w}`));

  // --- what's already there ---------------------------------------------------------
  const previous = readManifest(outputDir);
  const oldLayout = isOldLayout(outputDir);
  if (oldLayout && !options.migrate) {
    const files = oldLayoutFiles(outputDir);
    throw new GenerateError(
      `${outputDir} was generated by an older neucli, before generated code moved to src/neucli/.\n` +
      `  Run again with --migrate: it deletes the old generated files (${files.length}: src/components, src/pages,\n` +
      `  src/primitives, src/App.tsx...), replaces the old root files (index.html, src/main.tsx, src/index.css...)\n` +
      `  and keeps everything else, including your dependencies in package.json.`,
    );
  }

  const adopt = new Set<string>(oldLayout ? OLD_LAYOUT.replaced : []);
  const out = new Output(outputDir, previous, { force: options.force, keepStale: options.keepStale, adopt });

  // --- plan ----------------------------------------------------------------------------
  scaffoldProject(config, out, { previous, adoptDependencies: oldLayout });

  for (const name of usedComponents(config)) {
    const def = config.components![name];
    if (isFileComponent(def)) {
      const rel = `src/${fileComponentPath(def.file)}`;
      if (!fs.existsSync(path.join(outputDir, rel))) {
        if (rel.endsWith('.tsx')) out.seed(rel, fileComponentStub(name, def));
        else log(chalk.yellow(`  ! components.${name}.file: ${rel} doesn't exist yet`));
      }
      continue;
    }
    out.managed(`${OUT.components}/${name}.tsx`, componentSource(config, name, def));
  }

  for (const page of config.pages) {
    const name = pageComponentName(page.name);
    out.managed(`${OUT.pages}/${name}.tsx`, pageSource(config, page, pageParentFlows(config, page)));
  }
  out.managed(OUT.app, appSource(config, usesRouting(config)));

  // --- refuse before touching anything --------------------------------------------------
  const conflicts = out.conflicts();
  if (conflicts.length) {
    const shown = conflicts.slice(0, 8).map(f => `    ${f}`).join('\n');
    const more = conflicts.length > 8 ? `\n    ...and ${conflicts.length - 8} more` : '';
    throw new GenerateError(
      `${outputDir} has files neucli would overwrite but didn't write:\n${shown}${more}\n` +
      `  Generate into an empty folder, or run again with --force to overwrite them.`,
    );
  }

  // --- write ---------------------------------------------------------------------------
  if (oldLayout) {
    for (const rel of oldLayoutFiles(outputDir)) out.remove(rel);
    for (const d of [...OLD_LAYOUT.dirs, 'src/hooks']) removeEmptyDirs(path.join(outputDir, d), path.join(outputDir, d));
  }
  out.commit();
  const lock = path.join(outputDir, OUT.lock);
  const snapshot = fs.readFileSync(configPath, 'utf-8');
  if (!fs.existsSync(lock) || fs.readFileSync(lock, 'utf-8') !== snapshot) {
    fs.mkdirSync(path.dirname(lock), { recursive: true });
    fs.writeFileSync(lock, snapshot);
  }

  const r = out.report;
  const line = (icon: string, list: string[], label: string) => list.forEach(f => log(`    ${icon} ${f}${label}`));
  line(chalk.green('+'), r.added, '');
  line(chalk.yellow('~'), r.updated, '');
  line(chalk.cyan('*'), r.created, chalk.dim(' (created for you; yours from now on)'));
  line(chalk.red('✗'), r.removed, chalk.dim(' (removed)'));
  line(chalk.yellow('!'), r.skipped, chalk.yellow(' (edited by hand, left as is)'));
  return r;
}
